// Контакты из 1С: данные вымышленные.
import { describe, expect, it } from 'vitest';
import { parseContactsReport } from './contacts1c';

describe('ПСТ-1: справочник «Контрагенты» из 1С', () => {
  it('номера в +7XXXXXXXXXX; несколько в одной ячейке; повтор поставщика склеивается; мусор — на проверку', () => {
    const recs = parseContactsReport([
      ['Справочник: Контрагенты'], ['Выводить количество подчинённых записей: Да'],
      ['Контрагент', 'ИНН', 'Номер телефона'],
      ['ООО Тестовый опт', '', '8 (900) 000-00-01, +7 900 000 00 02'],
      ['ООО  Тестовый опт', '', '89000000001'],
      ['ИП Вымышленный', '', 'нет'],
      ['', '', '89000000009'],
      ['Без телефона', '', ''],
    ]);
    expect(recs).toEqual([
      { name: 'ООО Тестовый опт', phones: ['+79000000001', '+79000000002'], bad: [] },
      { name: 'ИП Вымышленный', phones: [], bad: ['нет'] },
      { name: 'Без телефона', phones: [], bad: [] },
    ]);
  });
  it('без нужных колонок — понятная ошибка', () => {
    expect(() => parseContactsReport([['Номенклатура', 'Цена']])).toThrow(/Контрагент/);
  });
});
