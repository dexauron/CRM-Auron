// Случаи перенесены из тестов старого каталога (catalog/tests/import.js); данные вымышленные.
import { describe, expect, it } from 'vitest';
import {
  detectReportType,
  nameKey,
  normCode,
  parseBarcodesReport,
  parseCountNum,
  parseDateCell,
  parsePriceNum,
  parsePriceReport,
  parseRetailList,
  parseStockReport,
} from './parse';

const PRICES = [
  ['Отчёт по ценам поставщиков'], [],
  ['Номенклатура', 'Код товара', 'Контрагент', 'Ед.', 'Цена', 'Период'],
  ['Snickers 50,5г', '1 463', 'Оптовик', 'упак (48)', '1 920,00', '01.08.2026'],
  ['Snickers 50,5г', '1 463', 'Своя Закупка', 'шт', '43,33', '01.08.2026'],
  ['Хлеб', '77', 'Пекарь', 'кг', '1 234,56', '02.08.2026'],
  ['', '', '', '', '', ''],
  ['Итого', '', '', '', '9 999,99', ''],
];

describe('КАТ-5: числа и коды из 1С', () => {
  it('деньги в любой записи', () => {
    expect(parsePriceNum('1 234,56')).toBe(1234.56);
    expect(parsePriceNum('1,234.56')).toBe(1234.56);
    expect(parsePriceNum('96,76')).toBe(96.76);
    expect(parsePriceNum('1,234')).toBe(1234);
    expect(parsePriceNum('45.00')).toBe(45);
    expect(parsePriceNum(89)).toBe(89);
    expect(parsePriceNum('0')).toBeNull();
    expect(parsePriceNum('')).toBeNull();
  });
  it('остаток и количество: запятая десятичная, минус допустим', () => {
    expect(parseCountNum('2,500')).toBe(2.5);
    expect(parseCountNum('1,000')).toBe(1);
    expect(parseCountNum('-3')).toBe(-3);
    expect(parseCountNum('48,000')).toBe(48);
    expect(parseCountNum('1 234,5')).toBe(1234.5);
  });
  it('код номенклатуры без разделителей тысяч', () => {
    expect(normCode('1 463')).toBe('1463');
    expect(normCode('1 463')).toBe('1463');
    expect(normCode('1,463')).toBe('1463');
    expect(normCode('A-17')).toBe('A-17');
  });
  it('даты: строка и серийный номер Excel', () => {
    expect(parseDateCell('01.08.2026')).toBe('2026-08-01');
    expect(parseDateCell('1.8.26')).toBe('2026-08-01');
    expect(parseDateCell(46235)).toBe('2026-08-01');
    expect(parseDateCell('не дата')).toBeNull();
  });
  it('название: слова в любом порядке, «200гр» = «200г», фасовки не склеиваются', () => {
    expect(nameKey('Чабан Сметана 25% стакан 200г')).toBe(nameKey('Сметана Чабан 25% стакан 200гр'));
    expect(nameKey('Huggies Трусики 38шт')).not.toBe(nameKey('Huggies Трусики 44шт'));
  });
});

describe('КАТ-5: тип отчёта по шапке', () => {
  const t = (rows: unknown[][]) => detectReportType(rows);
  it('узнаёт все отчёты старого каталога', () => {
    expect(t(PRICES)).toBe('prices');
    expect(t([['Справочник штрих кодов'], [], ['Штрих код', 'Единица', 'Номенклатура'], ['4600000000015', 'шт', 'Молоко']])).toBe('barcodes');
    expect(t([['Имя объекта: Штрих коды'], ['Выводить количество подчинённых записей: Да'], ['Штрих код', 'Номенклатура']])).toBe('barcodes');
    expect(t([['Остатки номенклатуры на конец дня: 12.08.2026'], [], ['Номенклатура', 'Код товара', 'Количество', 'Розничная цена']])).toBe('stock');
    expect(t([['Прайс-лист'], [], ['Номенклатура', 'Розничный тип цен'], ['Молоко', '89']])).toBe('retail');
    expect(t([['Отчёт по продажам', 'Период: 01.07.2026 - 31.07.2026'], [], ['Номенклатура', 'Код', 'Количество', 'Сумма продажи']])).toBe('sales');
    expect(t([['Контрагенты'], [], ['Контрагент', 'Номер телефона']])).toBe('contacts');
    expect(t([['Имя объекта: Единицы измерения'], [], ['Единица измерения', 'Коэффициент', 'Розничная цена единицы', 'Количество в упаковке']])).toBe('units');
    expect(t([['Неликвидные товары'], [], ['Номенклатура', 'Дата последнего поступления', 'Конечный остаток']])).toBe('stale');
    expect(t([['Номенклатура', 'Фото'], ['Молоко', 'https://example.org/1.jpg']])).toBe('photo');
  });
  it('мусор — не отчёт', () => {
    expect(t([['просто', 'какая-то'], ['таблица', 'без шапки']])).toBeNull();
  });
});

describe('КАТ-5: «Цены поставщиков»', () => {
  const items = parsePriceReport(PRICES);
  it('строка «Итого» не становится товаром, код очищен', () => {
    expect(items.map((i) => i.name)).toEqual(['Snickers 50,5г', 'Хлеб']);
    expect(items[0]?.code).toBe('1463');
  });
  it('цена у каждого поставщика со своей единицей; весовой — по «кг»', () => {
    const sn = items[0];
    expect(sn?.prices).toEqual([
      { supplier: 'Оптовик', price: 1920, unit: 'упак (48)', date: '2026-08-01' },
      { supplier: 'Своя Закупка', price: 43.33, unit: 'шт', date: '2026-08-01' },
    ]);
    expect(items[1]?.weighted).toBe(true);
    expect(items[1]?.prices[0]?.price).toBe(1234.56);
  });
  it('у поставщика цена за штуку и за упаковку хранятся отдельно', () => {
    const [item] = parsePriceReport([
      ['Номенклатура', 'Код товара', 'Контрагент', 'Ед.', 'Цена', 'Период'],
      ['Молоко', '1', 'Молзавод', 'шт', '180,00', '01.10.2026'],
      ['Молоко', '1', 'Молзавод', 'упак (12)', '2 100,00', '01.10.2026'],
    ]);
    expect(item?.prices.map((p) => [p.unit, p.price])).toEqual([['шт', 180], ['упак (12)', 2100]]);
  });

  it('у поставщика остаётся самая свежая цена', () => {
    const [item] = parsePriceReport([
      ['Номенклатура', 'Код товара', 'Контрагент', 'Ед.', 'Цена', 'Период'],
      ['Молоко', '1', 'Опт', 'шт', '50', '01.08.2026'],
      ['Молоко', '1', 'Опт', 'шт', '55', '15.08.2026'],
      ['Молоко', '1', 'Опт', 'шт', '52', '10.08.2026'],
    ]);
    expect(item?.prices).toEqual([{ supplier: 'Опт', price: 55, unit: 'шт', date: '2026-08-15' }]);
  });
  it('без шапки — понятная ошибка', () => {
    expect(() => parsePriceReport([['просто'], ['таблица']])).toThrow(/заголовков/);
  });
});

describe('КАТ-5: остатки, штрихкоды, прайс-лист', () => {
  it('остатки: минус, «2,500» = 2,5 кг, «1,000» = 1 шт, дата из шапки, итоги пропускаются', () => {
    const { recs, stockAt } = parseStockReport([
      ['Остатки номенклатуры на конец дня: 12.08.2026'], [],
      ['Номенклатура', 'Код товара', 'Количество', 'Розничная цена'],
      ['Молоко', '55', '-3', '89'], ['Сыр', '56', '2,500', '450'], ['Вода', '57', '1,000', '35'],
      ['Итого', '', '999', ''],
    ]);
    expect(stockAt).toBe('2026-08-12');
    expect(recs.map((r) => [r.name, r.stock, r.retail])).toEqual([['Молоко', -3, 89], ['Сыр', 2.5, 450], ['Вода', 1, 35]]);
  });
  it('справочник штрихкодов: единица и код сохраняются', () => {
    expect(parseBarcodesReport([
      ['Справочник штрих кодов'], [],
      ['Штрих код', 'Единица', 'Номенклатура'],
      ['4600000000015', 'шт', 'Сметана Чабан 25% стакан 200гр'],
      ['4600000000022', 'упак (24)', 'Вода 0,5'],
    ])).toEqual([
      { barcode: '4600000000015', name: 'Сметана Чабан 25% стакан 200гр', code: null, unit: 'шт' },
      { barcode: '4600000000022', name: 'Вода 0,5', code: null, unit: 'упак (24)' },
    ]);
  });
  it('прайс-лист: строки без цены — группы, артикул из названия, дата из шапки', () => {
    const { recs, fileDate } = parseRetailList([
      ['Прайс-лист на 17 июля 2026 г.'], [],
      ['Номенклатура', 'Розничный тип цен'],
      ['Игрушки', ''],
      ['Кукла Арт.st-917', '1 250,00'],
      ['Итого', '1 250,00'],
    ]);
    expect(fileDate).toBe('2026-07-17');
    expect(recs).toEqual([{ name: 'Кукла Арт.st-917', article: 'st-917', group: 'Игрушки', retail: 1250 }]);
  });
});
